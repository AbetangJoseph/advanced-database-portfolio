CREATE OR REPLACE FUNCTION validate_fare_route_stations()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    origin_sequence integer;
    destination_sequence integer;
BEGIN
    SELECT stop_sequence INTO origin_sequence
    FROM route_stations
    WHERE route_id = NEW.route_id AND station_id = NEW.origin_station_id;

    SELECT stop_sequence INTO destination_sequence
    FROM route_stations
    WHERE route_id = NEW.route_id AND station_id = NEW.destination_station_id;

    IF origin_sequence IS NULL OR destination_sequence IS NULL THEN
        RAISE EXCEPTION 'Fare stations must both belong to route %', NEW.route_id;
    END IF;

    IF origin_sequence >= destination_sequence THEN
        RAISE EXCEPTION 'Fare destination must occur after its origin on route %', NEW.route_id;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_fare_route
BEFORE INSERT OR UPDATE ON fares
FOR EACH ROW EXECUTE FUNCTION validate_fare_route_stations();

CREATE OR REPLACE FUNCTION validate_ticket_assignment()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    origin_sequence integer;
    destination_sequence integer;
    journey_train_id bigint;
    seat_train_id bigint;
    journey_route_id bigint;
    origin_station_id bigint;
    destination_station_id bigint;
    seat_coach_class varchar(10);
    passenger_category varchar(6);
    selected_fare fares%ROWTYPE;
BEGIN
    SELECT stop_sequence, station_id INTO origin_sequence, origin_station_id
    FROM journey_stops
    WHERE journey_stop_id = NEW.origin_journey_stop_id AND journey_id = NEW.journey_id;

    SELECT stop_sequence, station_id INTO destination_sequence, destination_station_id
    FROM journey_stops
    WHERE journey_stop_id = NEW.destination_journey_stop_id AND journey_id = NEW.journey_id;

    IF origin_sequence IS NULL OR destination_sequence IS NULL THEN
        RAISE EXCEPTION 'Both ticket stops must belong to journey %', NEW.journey_id;
    END IF;

    IF origin_sequence >= destination_sequence THEN
        RAISE EXCEPTION 'Ticket destination must occur after boarding stop';
    END IF;

    SELECT train_id, route_id INTO journey_train_id, journey_route_id
    FROM journeys
    WHERE journey_id = NEW.journey_id;

    SELECT c.train_id, c.coach_class INTO seat_train_id, seat_coach_class
    FROM seats AS s
    JOIN coaches AS c ON c.coach_id = s.coach_id
    WHERE s.seat_id = NEW.seat_id;

    IF journey_train_id IS DISTINCT FROM seat_train_id THEN
        RAISE EXCEPTION 'Seat % does not belong to the train assigned to journey %', NEW.seat_id, NEW.journey_id;
    END IF;

    SELECT passenger_type INTO passenger_category
    FROM booking_passengers
    WHERE passenger_id = NEW.passenger_id AND booking_id = NEW.booking_id;

    SELECT * INTO selected_fare
    FROM fares
    WHERE fare_id = NEW.fare_id;

    IF selected_fare.route_id IS DISTINCT FROM journey_route_id
       OR selected_fare.origin_station_id IS DISTINCT FROM origin_station_id
       OR selected_fare.destination_station_id IS DISTINCT FROM destination_station_id
       OR selected_fare.coach_class IS DISTINCT FROM seat_coach_class
       OR selected_fare.passenger_type IS DISTINCT FROM passenger_category THEN
        RAISE EXCEPTION 'Fare % does not match the ticket route, stations, coach class or passenger type', NEW.fare_id;
    END IF;

    IF NEW.charged_fare IS DISTINCT FROM selected_fare.amount THEN
        RAISE EXCEPTION 'Charged fare % does not match selected fare amount %', NEW.charged_fare, selected_fare.amount;
    END IF;

    NEW.boarding_sequence := origin_sequence;
    NEW.alighting_sequence := destination_sequence;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_validate_ticket_assignment
BEFORE INSERT OR UPDATE OF journey_id, origin_journey_stop_id, destination_journey_stop_id, seat_id, fare_id, charged_fare, passenger_id, booking_id ON tickets
FOR EACH ROW EXECUTE FUNCTION validate_ticket_assignment();

COMMENT ON CONSTRAINT ex_no_overlapping_seat_ticket ON tickets IS 'Prevents overlapping active tickets for the same seat and dated journey.';

