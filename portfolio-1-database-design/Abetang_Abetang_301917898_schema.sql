CREATE TABLE users (
    user_id             uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email               varchar(254) NOT NULL UNIQUE,
    phone               varchar(25) NOT NULL,
    password_hash       varchar(255) NOT NULL,
    first_name          varchar(60) NOT NULL,
    last_name           varchar(60) NOT NULL,
    role                varchar(15) NOT NULL DEFAULT 'PASSENGER',
    account_status      varchar(10) NOT NULL DEFAULT 'ACTIVE',
    created_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_user_email CHECK (position('@' IN email) > 1),
    CONSTRAINT ck_user_role CHECK (role IN ('PASSENGER', 'AGENT', 'STATION_STAFF', 'CONDUCTOR', 'OPERATIONS', 'FINANCE', 'ADMIN')),
    CONSTRAINT ck_user_status CHECK (account_status IN ('ACTIVE', 'LOCKED', 'DISABLED'))
);

CREATE TABLE stations (
    station_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_code        varchar(6) NOT NULL UNIQUE,
    station_name        varchar(120) NOT NULL,
    city                varchar(80) NOT NULL,
    state_name          varchar(80) NOT NULL,
    active              boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_station_code CHECK (station_code ~ '^[A-Z0-9]{3,6}$')
);

CREATE TABLE routes (
    route_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_code          varchar(12) NOT NULL UNIQUE,
    route_name          varchar(120) NOT NULL,
    service_name        varchar(80) NOT NULL,
    ticketing_provider  varchar(120) NOT NULL,
    booking_url         varchar(255),
    active              boolean NOT NULL DEFAULT true,
    CONSTRAINT ck_route_code CHECK (route_code ~ '^[A-Z0-9-]{3,12}$')
);

CREATE TABLE route_stations (
    route_id            bigint NOT NULL REFERENCES routes(route_id) ON DELETE CASCADE,
    station_id          bigint NOT NULL REFERENCES stations(station_id),
    stop_sequence       integer NOT NULL,
    distance_km         numeric(7,2) NOT NULL DEFAULT 0,
    PRIMARY KEY (route_id, station_id),
    CONSTRAINT uq_route_stop_sequence UNIQUE (route_id, stop_sequence),
    CONSTRAINT ck_route_stop_sequence CHECK (stop_sequence > 0),
    CONSTRAINT ck_route_distance CHECK (distance_km >= 0)
);

CREATE TABLE trains (
    train_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_number        varchar(20) NOT NULL UNIQUE,
    train_name          varchar(100),
    model               varchar(100) NOT NULL,
    active              boolean NOT NULL DEFAULT true
);

CREATE TABLE coaches (
    coach_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id            bigint NOT NULL REFERENCES trains(train_id) ON DELETE CASCADE,
    coach_number        varchar(10) NOT NULL,
    coach_class         varchar(10) NOT NULL,
    seat_capacity       integer NOT NULL,
    active              boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_train_coach UNIQUE (train_id, coach_number),
    CONSTRAINT ck_coach_class CHECK (coach_class IN ('STANDARD', 'BUSINESS', 'FIRST')),
    CONSTRAINT ck_coach_capacity CHECK (seat_capacity > 0)
);

CREATE TABLE seats (
    seat_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coach_id            bigint NOT NULL REFERENCES coaches(coach_id) ON DELETE CASCADE,
    seat_number         varchar(5) NOT NULL,
    seat_position       varchar(8) NOT NULL,
    accessible          boolean NOT NULL DEFAULT false,
    active              boolean NOT NULL DEFAULT true,
    CONSTRAINT uq_coach_seat UNIQUE (coach_id, seat_number),
    CONSTRAINT ck_seat_number CHECK (seat_number ~ '^[1-9][0-9]?[A-Z]$'),
    CONSTRAINT ck_seat_position CHECK (seat_position IN ('WINDOW', 'MIDDLE', 'AISLE'))
);

CREATE TABLE journeys (
    journey_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_number      varchar(20) NOT NULL,
    route_id            bigint NOT NULL REFERENCES routes(route_id),
    train_id            bigint NOT NULL REFERENCES trains(train_id),
    planned_departure   timestamptz NOT NULL,
    planned_arrival     timestamptz NOT NULL,
    actual_departure    timestamptz,
    actual_arrival      timestamptz,
    status              varchar(12) NOT NULL DEFAULT 'SCHEDULED',
    CONSTRAINT uq_dated_service UNIQUE (service_number, planned_departure),
    CONSTRAINT ck_journey_time CHECK (planned_arrival > planned_departure),
    CONSTRAINT ck_journey_actual_time CHECK (actual_arrival IS NULL OR actual_departure IS NULL OR actual_arrival > actual_departure),
    CONSTRAINT ck_journey_status CHECK (status IN ('SCHEDULED', 'BOARDING', 'DEPARTED', 'ARRIVED', 'DELAYED', 'CANCELLED'))
);

CREATE TABLE journey_stops (
    journey_stop_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journey_id          bigint NOT NULL REFERENCES journeys(journey_id) ON DELETE CASCADE,
    station_id          bigint NOT NULL REFERENCES stations(station_id),
    stop_sequence       integer NOT NULL,
    planned_arrival     timestamptz,
    planned_departure   timestamptz,
    actual_arrival      timestamptz,
    actual_departure    timestamptz,
    platform_code       varchar(12),
    CONSTRAINT uq_journey_station UNIQUE (journey_id, station_id),
    CONSTRAINT uq_journey_stop_sequence UNIQUE (journey_id, stop_sequence),
    CONSTRAINT uq_journey_stop_pair UNIQUE (journey_stop_id, journey_id),
    CONSTRAINT ck_journey_stop_sequence CHECK (stop_sequence > 0),
    CONSTRAINT ck_stop_has_time CHECK (planned_arrival IS NOT NULL OR planned_departure IS NOT NULL)
);

CREATE TABLE bookings (
    booking_id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    booking_reference   varchar(12) NOT NULL UNIQUE,
    user_id             uuid NOT NULL REFERENCES users(user_id),
    sales_channel       varchar(10) NOT NULL,
    status              varchar(10) NOT NULL DEFAULT 'HELD',
    hold_expires_at     timestamptz,
    total_amount        numeric(12,2) NOT NULL DEFAULT 0,
    currency_code       varchar(3) NOT NULL DEFAULT 'NGN',
    booked_at           timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ck_booking_reference CHECK (booking_reference ~ '^[A-Z0-9]{6,12}$'),
    CONSTRAINT ck_booking_channel CHECK (sales_channel IN ('WEB', 'MOBILE', 'COUNTER', 'AGENT')),
    CONSTRAINT ck_booking_status CHECK (status IN ('HELD', 'CONFIRMED', 'CANCELLED', 'EXPIRED')),
    CONSTRAINT ck_booking_hold CHECK (status <> 'HELD' OR hold_expires_at IS NOT NULL),
    CONSTRAINT ck_booking_amount CHECK (total_amount >= 0),
    CONSTRAINT ck_booking_currency CHECK (currency_code ~ '^[A-Z]{3}$')
);

CREATE TABLE booking_passengers (
    passenger_id       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    booking_id         uuid NOT NULL REFERENCES bookings(booking_id) ON DELETE CASCADE,
    title              varchar(5),
    first_name         varchar(60) NOT NULL,
    last_name          varchar(60) NOT NULL,
    date_of_birth      date NOT NULL,
    passenger_type     varchar(6) NOT NULL,
    identity_type      varchar(18) NOT NULL,
    identity_reference varchar(120) NOT NULL,
    identity_last4     varchar(4) NOT NULL,
    identity_verified boolean NOT NULL DEFAULT false,
    CONSTRAINT uq_passenger_booking UNIQUE (passenger_id, booking_id),
    CONSTRAINT ck_passenger_title CHECK (title IS NULL OR title IN ('MR', 'MRS', 'MS', 'MISS', 'DR')),
    CONSTRAINT ck_passenger_type CHECK (passenger_type IN ('ADULT', 'CHILD', 'INFANT')),
    CONSTRAINT ck_identity_type CHECK (identity_type IN ('NIN', 'PASSPORT', 'DRIVERS_LICENCE', 'VOTERS_CARD')),
    CONSTRAINT ck_identity_last4 CHECK (identity_last4 ~ '^[A-Z0-9]{4}$')
);

CREATE TABLE fares (
    fare_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id            bigint NOT NULL REFERENCES routes(route_id),
    origin_station_id   bigint NOT NULL REFERENCES stations(station_id),
    destination_station_id bigint NOT NULL REFERENCES stations(station_id),
    coach_class         varchar(10) NOT NULL,
    passenger_type      varchar(6) NOT NULL,
    amount              numeric(12,2) NOT NULL,
    currency_code       varchar(3) NOT NULL DEFAULT 'NGN',
    effective_from      date NOT NULL,
    effective_to        date,
    CONSTRAINT uq_effective_fare UNIQUE (route_id, origin_station_id, destination_station_id, coach_class, passenger_type, effective_from),
    CONSTRAINT ck_fare_stations CHECK (origin_station_id <> destination_station_id),
    CONSTRAINT ck_fare_class CHECK (coach_class IN ('STANDARD', 'BUSINESS', 'FIRST')),
    CONSTRAINT ck_fare_passenger CHECK (passenger_type IN ('ADULT', 'CHILD', 'INFANT')),
    CONSTRAINT ck_fare_amount CHECK (amount >= 0),
    CONSTRAINT ck_fare_currency CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_fare_dates CHECK (effective_to IS NULL OR effective_to >= effective_from)
);

CREATE TABLE tickets (
    ticket_id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number               varchar(20) NOT NULL UNIQUE,
    qr_token                    varchar(80) NOT NULL UNIQUE,
    booking_id                  uuid NOT NULL REFERENCES bookings(booking_id),
    passenger_id                uuid NOT NULL,
    journey_id                  bigint NOT NULL REFERENCES journeys(journey_id),
    origin_journey_stop_id      bigint NOT NULL,
    destination_journey_stop_id bigint NOT NULL,
    seat_id                     bigint NOT NULL REFERENCES seats(seat_id),
    fare_id                     bigint NOT NULL REFERENCES fares(fare_id),
    boarding_sequence           integer NOT NULL,
    alighting_sequence          integer NOT NULL,
    occupied_range              int4range GENERATED ALWAYS AS (int4range(boarding_sequence, alighting_sequence, '[)')) STORED,
    charged_fare                numeric(12,2) NOT NULL,
    currency_code               varchar(3) NOT NULL DEFAULT 'NGN',
    status                      varchar(10) NOT NULL DEFAULT 'HELD',
    held_until                  timestamptz,
    issued_at                   timestamptz,
    used_at                     timestamptz,
    CONSTRAINT uq_ticket_passenger_journey UNIQUE (passenger_id, journey_id),
    CONSTRAINT fk_ticket_passenger_booking FOREIGN KEY (passenger_id, booking_id)
        REFERENCES booking_passengers(passenger_id, booking_id),
    CONSTRAINT fk_ticket_origin_journey FOREIGN KEY (origin_journey_stop_id, journey_id)
        REFERENCES journey_stops(journey_stop_id, journey_id),
    CONSTRAINT fk_ticket_destination_journey FOREIGN KEY (destination_journey_stop_id, journey_id)
        REFERENCES journey_stops(journey_stop_id, journey_id),
    CONSTRAINT ck_ticket_range CHECK (boarding_sequence < alighting_sequence),
    CONSTRAINT ck_ticket_fare CHECK (charged_fare >= 0),
    CONSTRAINT ck_ticket_currency CHECK (currency_code ~ '^[A-Z]{3}$'),
    CONSTRAINT ck_ticket_status CHECK (status IN ('HELD', 'ISSUED', 'CANCELLED', 'EXPIRED', 'USED', 'REFUNDED')),
    CONSTRAINT ck_ticket_hold CHECK ((status = 'HELD' AND held_until IS NOT NULL) OR (status <> 'HELD' AND held_until IS NULL)),
    CONSTRAINT ex_no_overlapping_seat_ticket EXCLUDE USING gist (
        journey_id WITH =,
        seat_id WITH =,
        occupied_range WITH &&
    ) WHERE (status IN ('HELD', 'ISSUED', 'USED'))
);

